export const assessmentOptions = [
  { value: 'yes', label: 'አዎ', points: 5 },
  { value: 'partial', label: 'በከፊል', points: 2 },
  { value: 'no', label: 'አይ', points: 0 }
]; 
/** @param {Record<string, string>} answers */
export function gradeAssessment(answers) {  let score = 0;

  for (const question of assessmentQuestions) {
    const answer = answers[question.id];
    const option = assessmentOptions.find(
      (item) => item.value === answer
    );

    if (!option) {
      throw new Error(`Invalid answer for ${question.id}`);
    }

    score += option.points;
  }

  // Registration and licensing are mandatory readiness checks.
  const mandatoryRequirementsMet =
    answers.q1 === 'yes' &&
    answers.q2 === 'yes';

  const passed = score >= 80 && mandatoryRequirementsMet;

  return {
    score,
    passed,
    status: passed ? 'passed' : 'needs_support',
    message: passed
      ? 'You passed the preliminary assessment. You may proceed to document verification.'
      : 'Your business requires further review and support. Our facilitation team will arrange a visit before reassessment.'
  };
}
